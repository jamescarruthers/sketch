// Data model contract: docs/SPEC.md section 3, verbatim. Coordinates are millimetres, Y up; angles radians.

export type Id = string;
export interface Vec2 { x: number; y: number }
export type LineType = 'normal' | 'construction' | 'centerline';

/** Every position in a sketch is a Point. Curves reference points by id. */
export interface Point {
  id: Id; x: number; y: number;
  /** Created by the Point tool: survives deletion of curves, is drawn and exported as a point. */
  explicit?: boolean;
  /** Set by Fix/UnFix. */
  fixed?: boolean;
  /** Owning curve, if any (centres, endpoints, fit points, handles). */
  owner?: Id;
  /** A helper that is drawn all the same, as a chamfer's virtual corner is [ref SKT-ADD-CHAMFERS]. */
  shown?: boolean;
  /** Projected from another sketch: locked, purple, follows its source. */
  projected?: { sketchId: Id; pointId: Id };
  /** Layer of a point with no curve. A curve's points follow its layer. */
  layer?: Id;
}

interface CurveBase {
  id: Id;
  lineType: LineType;
  layer: Id;
  fixed?: boolean;
  /** Projected geometry: locked, purple. Holds its source for associativity. */
  projected?: { sketchId: Id; curveId: Id } | { origin: 'x' | 'y' };
  /** Generated by a Feature (offset): regenerated after solve, immovable in the solver. */
  derivedFrom?: Id;
}
export interface Line extends CurveBase {
  type: 'line'; a: Id; b: Id;
  /** Edge of this text's frame: shares its corner points, and lives and dies with it. */
  frameOf?: Id;
}
export interface Circle extends CurveBase { type: 'circle'; c: Id; r: number }
/** Always counter-clockwise from a to b. Radius is |c-a|. */
export interface Arc extends CurveBase { type: 'arc'; c: Id; a: Id; b: Id }
/** major, minor are the axis end points. Solver keeps c-major perpendicular to c-minor. */
export interface Ellipse extends CurveBase { type: 'ellipse'; c: Id; major: Id; minor: Id }
/** Result of trimming an ellipse. Counter-clockwise from a to b. */
export interface EllipticalArc extends CurveBase { type: 'ellipticalArc'; c: Id; major: Id; minor: Id; a: Id; b: Id }
/** Interpolating cubic spline (chord-length parameterised, natural ends unless a handle is active). */
export interface FitSpline extends CurveBase {
  type: 'fitSpline'; pts: Id[]; closed: boolean;
  /** Tangent handle point per fit point, or null when inactive. */
  handles: (Id | null)[];
}
export type SplineDegree = 1 | 2 | 3 | 4 | 5 | 6 | 7 | 8 | 9;
/** Clamped uniform B-spline. */
export interface ControlSpline extends CurveBase {
  type: 'controlSpline'; pts: Id[]; degree: SplineDegree;
  /** Made by Blend Curve: its controls are hidden until the spline is selected. */
  blend?: boolean;
}
/** Rational quadratic: a, b end points, v vertex, rho in (0,1). */
export interface Conic extends CurveBase { type: 'conic'; a: Id; b: Id; v: Id; rho: number }
export interface TextEntity extends CurveBase {
  type: 'text'; mode: 'frame' | 'path';
  /** Its name in Change Parameters, Text1 and so on. Kept, so {Text2_text} still means it when Text1 goes. */
  parameter?: string;
  text: string; font: string; bold: boolean; italic: boolean;
  height: number; spacing: number; // percent
  /** Height as typed in Change Parameters, when it is more than a number. */
  heightExpression?: string;
  flipH: boolean; flipV: boolean;
  halign: 'left' | 'center' | 'right'; valign: 'top' | 'middle' | 'bottom';
  /** frame: 4 corner points of the constrained frame rectangle (ccw from bottom-left). */
  frame?: [Id, Id, Id, Id];
  /** path: curve followed. */
  path?: Id; above?: boolean; fitToPath?: boolean;
  /** path: how far along the path the text has been moved, in mm. */
  offset?: number;
}
export type Curve = Line | Circle | Arc | Ellipse | EllipticalArc | FitSpline | ControlSpline | Conic | TextEntity;

export type ConstraintType =
  | 'coincident'      // [point, point] or [point, curve]
  | 'horizontal'      // [line] or [point, point]
  | 'vertical'        // [line] or [point, point]
  | 'parallel'        // [line, line]
  | 'perpendicular'   // [line, line] or [line, arc/circle] (radial)
  | 'tangent'         // [curve, curve]
  | 'equal'           // [line, line] lengths or [circle/arc, circle/arc] radii
  | 'midpoint'        // [point, line/arc]
  | 'concentric'      // [circle/arc/ellipse, circle/arc/ellipse]
  | 'collinear'       // [line, line]
  | 'symmetric'       // [a, b, axisLine]: a,b are points or matching curves
  | 'curvature'       // [spline, curve]
  | 'offsetCopy'      // [p, q]; q = p + {dx,dy}. Rectangular patterns.
  | 'rotatedCopy';    // [c, p, q]; q = p rotated about c by angle. Circular patterns.
export interface Constraint {
  id: Id; type: ConstraintType; refs: Id[];
  dx?: number; dy?: number; angle?: number;
  /** Which end/side, chosen once from geometry at creation, so solves don't flip. */
  variant?: number;
  /** Feature that owns this constraint; hidden from glyphs, removed with the feature. */
  feature?: Id;
  /** Set when the refs span layers: the layer whose side follows and which owns the constraint. */
  dependentLayer?: Id;
}

export type DimensionKind =
  | 'distance'    // [p, q] aligned
  | 'horizontal'  // [p, q]
  | 'vertical'    // [p, q]
  | 'pointLine'   // [p, line]
  | 'lineLine'    // [line, line], parallel lines
  | 'angle'       // [line, line]
  | 'radius'      // [arc/circle]
  | 'diameter'    // [arc/circle]; also [centerline, point] revolve diameter
  | 'arcLength'   // [arc]
  | 'ellipseAxis'  // [ellipse, 'major'|'minor' via variant]
  | 'tangentLine'   // [circle/arc, line]: rim to line. variant bit 0: 0 near rim, 1 far rim
  | 'tangentRounds'; // [circle/arc, circle/arc]: rim to rim along the line of centres. variant as above, per ref
export interface Dimension {
  id: Id; kind: DimensionKind; refs: Id[];
  name: string;         // d1, d2, ... unique per document
  expression: string;   // "25.4 mm", "d1 * 2"
  value: number;        // resolved, mm or radians
  driving: boolean;     // false = Driven: shown "(12.00)", read only, not sent to solver
  label: Vec2;          // sketch-space label position
  variant?: number;     // e.g. axis of ellipse, which quadrant of an angle
  feature?: Id;
  /** Set when the refs span layers: the layer whose side follows and which owns the dimension. */
  dependentLayer?: Id;
}

export type Feature =
  | { id: Id; type: 'rectPattern'; sources: Id[]; dirs: [Vec2, Vec2 | null]; distanceType: 'extent' | 'spacing';
      quantity: [number, number]; distance: [number, number]; direction: ['one' | 'symmetric', 'one' | 'symmetric'];
      suppressed: string[]; instances: Record<string, Id[]> }
  | { id: Id; type: 'circPattern'; sources: Id[]; center: Id; spacing: 'full' | 'angle' | 'symmetric';
      angle: number; quantity: number; suppressed: string[]; instances: Record<string, Id[]> }
  | { id: Id; type: 'offset'; sources: Id[]; distance: number; side: 1 | -1; dimension: Id | null; outputs: Id[]; matchTopology?: boolean }
  | { id: Id; type: 'mirror'; axis: Id; pairs: [Id, Id][] };

/** The three origin planes, by name. Each is a Frame: see PLANE_FRAMES in frames.ts. */
export type Plane = 'XY' | 'YZ' | 'ZX';
export interface Vec3 { x: number; y: number; z: number }
/**
 * Where a sketch lies in 3D, in mm: the 3D position of its origin, and its x and y axes as orthonormal
 * directions. The normal is u x v. A sketch point (x, y) is at o + x u + y v.
 */
export interface Frame { o: Vec3; u: Vec3; v: Vec3 }
export interface Sketch {
  id: Id; name: string; frame: Frame; visible: boolean;
  points: Record<Id, Point>;
  curves: Record<Id, Curve>;
  constraints: Record<Id, Constraint>;
  dimensions: Record<Id, Dimension>;
  features: Record<Id, Feature>;
}
/** With unit 'text' the expression is the text itself, and value is unused. */
export interface UserParameter { name: string; expression: string; value: number; comment: string; unit: 'mm' | 'deg' | '' | 'text' }
/** Design-wide, spanning sketches. */
export interface Layer {
  id: Id; name: string;
  /** #rrggbb. */
  color: string;
  visible: boolean; locked: boolean;
}
export const DESIGN_VERSION = 3;
export interface Design {
  version: typeof DESIGN_VERSION; name: string;
  sketches: Record<Id, Sketch>;
  order: Id[];
  parameters: UserParameter[];
  units: 'mm' | 'cm' | 'm' | 'in' | 'ft';
  nextId: number;
  /** The next number for a new dimension and a new parameter. Only ever goes up: a name is not used twice. */
  names?: { d: number; p: number };
  /** In list order: the top of the list is drawn last. */
  layers: Layer[];
  activeLayer: Id;
}

/** Reserved point at 0,0. Exists in every sketch without being stored. */
export const ORIGIN = 'origin';
/** Reserved fixed infinite construction line along X. Never stored. */
export const AXIS_X = 'axis-x';
/** Reserved fixed infinite construction line along Y. Never stored. */
export const AXIS_Y = 'axis-y';
